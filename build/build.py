"""
Build the single-file, offline character generator.

  1. Renders the PDF template + field layout (make_template.py)
  2. Writes src/template-data.js (base64 template + field layout) for the dev page
  3. Inlines every <script src> / <link rel=stylesheet> from src/index.html into
     dist/Crows_Character_Generator.html

Requires Python 3 with reportlab and pypdf (build time only; the output HTML needs nothing).
Usage (from the project root):  python build/build.py [path to official inventory sheet PDF]
"""
import base64
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, 'build', 'out')
DIST = os.path.join(ROOT, 'dist')
DEFAULT_SHEET = os.path.join(ROOT, 'assets', 'Crows Inventory Sheet for Playtest 2.pdf')


def main():
    sheet = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SHEET
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(DIST, exist_ok=True)
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'build', 'make_template.py'), sheet, OUT])

    with open(os.path.join(OUT, 'template.pdf'), 'rb') as f:
        b64 = base64.b64encode(f.read()).decode('ascii')
    with open(os.path.join(OUT, 'field_layout.json')) as f:
        fields = json.load(f)
    with open(os.path.join(SRC, 'template-data.js'), 'w', newline='\n') as f:
        f.write('/* Generated by build/build.py - do not edit. */\n')
        f.write('var CROWS_FIELDS = %s;\n' % json.dumps(fields, separators=(',', ':')))
        f.write('var CROWS_TEMPLATE_B64 = "%s";\n' % b64)

    with open(os.path.join(SRC, 'index.html'), encoding='utf-8') as f:
        html = f.read()

    def read(rel):
        with open(os.path.normpath(os.path.join(SRC, rel)), encoding='utf-8') as fh:
            return fh.read()

    def inline_script(m):
        code = read(m.group(1))
        assert '</script' not in code.lower(), m.group(1) + ' contains </script'
        return '<script>\n' + code + '\n</script>'

    def inline_css(m):
        return '<style>\n' + read(m.group(1)) + '\n</style>'

    html = re.sub(r'<script src="([^"]+)"></script>', inline_script, html)
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', inline_css, html)
    assert 'src="' not in html.split('<body>')[0] and not re.search(r'<script src=', html)

    out = os.path.join(DIST, 'Crows_Character_Generator.html')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    print('wrote', out, '(%d KB)' % (os.path.getsize(out) // 1024))


if __name__ == '__main__':
    main()
