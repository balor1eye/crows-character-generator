"""
Build the single-file, offline Crows Ref Screen.

  1. Converts the rules summary (docs/CROWS_PT2_RULES.md) into ref/src/rules-text.js for the Rules tab
  2. Inlines every <script src> / <link rel=stylesheet> from ref/src/index.html into
     dist/Crows_Ref_Screen.html

Needs only Python 3 (no packages). Usage (from the project root):  python ref/build/build.py [path to rules .md]
"""
import json
import os
import re
import sys

REF = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(REF)
SRC = os.path.join(REF, 'src')
DIST = os.path.join(ROOT, 'dist')  # the folder GitHub Pages publishes
DEFAULT_RULES = os.path.join(ROOT, 'docs', 'CROWS_PT2_RULES.md')


def main():
    rules = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_RULES
    rules_js = os.path.join(SRC, 'rules-text.js')
    if os.path.exists(rules):
        with open(rules, encoding='utf-8') as f:
            text = f.read()
        with open(rules_js, 'w', encoding='utf-8', newline='\n') as f:
            f.write('/* Generated by ref/build/build.py from %s - do not edit. */\n' % os.path.basename(rules))
            # json.dumps escapes quotes and newlines; "</" is escaped so the text can't close the inlined <script>.
            f.write('var REF_RULES = %s;\n' % json.dumps(text, ensure_ascii=False).replace('</', '<\\/'))
    elif not os.path.exists(rules_js):
        sys.exit('rules summary not found: %s' % rules)
    else:
        print('rules summary not found; keeping the existing', rules_js)

    with open(os.path.join(SRC, 'index.html'), encoding='utf-8') as f:
        html = f.read()

    def read(rel):
        with open(os.path.normpath(os.path.join(SRC, rel)), encoding='utf-8') as fh:
            return fh.read()

    def inline_script(m):
        code = read(m.group(1))
        assert '</script' not in code.lower(), m.group(1) + ' contains </script'
        return '<script>\n' + code + '\n</script>'

    def inline_css(m):
        return '<style>\n' + read(m.group(1)) + '\n</style>'

    html = re.sub(r'<script src="([^"]+)"></script>', lambda m: inline_script(m), html)
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', lambda m: inline_css(m), html)
    assert not re.search(r'<script src=|<link rel="stylesheet"', html)

    os.makedirs(DIST, exist_ok=True)
    out = os.path.join(DIST, 'Crows_Ref_Screen.html')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    print('wrote', out, '(%d KB)' % (os.path.getsize(out) // 1024))


if __name__ == '__main__':
    main()
